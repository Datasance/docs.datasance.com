#!/usr/bin/env node
/**
 * Patch versioned sidebars for ioFog builds.
 *
 * The ioFog preset excludes potctl CLI docs. v3.9.1 and v3.9.0 use
 * reference/cli/potctl, and v3.8.0 uses potctl/cli. Those snapshots include
 * iofogctl pages, so those categories are retargeted. Get Started CLI
 * categories keep their doc ids and take the iofogctl label. v3.7.x has no
 * iofogctl CLI snapshot, so the CLI Reference category is removed.
 *
 * Usage: DOCUSAURUS_DISTRIBUTION=iofog node scripts/flavor-version-sidebar.js patch|restore
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SIDEBARS_DIR = path.join(ROOT, 'versioned_sidebars');

const POTCTL_CLI_DIRS = {
  'potctl/cli': 'iofogctl/cli',
  'reference/cli/potctl': 'reference/cli/iofogctl',
};

const FILES = [
  {file: 'version-v3.9.2-sidebars.json', mode: 'retarget'},
  {file: 'version-v3.9.1-sidebars.json', mode: 'retarget'},
  {file: 'version-v3.9.0-sidebars.json', mode: 'retarget'},
  {file: 'version-v3.8.0-sidebars.json', mode: 'retarget'},
  {file: 'version-v3.7.0-sidebars.json', mode: 'strip'},
  {file: 'version-v3.7.1-sidebars.json', mode: 'strip'},
  {file: 'version-v3.7.3-sidebars.json', mode: 'strip'},
];

function backupPath(file) {
  return path.join(SIDEBARS_DIR, `${file}.datasance.bak`);
}

function isCliGuidesCategory(item) {
  if (!item || item.type !== 'category' || item.label !== 'potctl') {
    return false;
  }
  return (item.items || []).some(
    (child) =>
      child.type === 'doc' &&
      (child.id === 'get-started/cli/introduction' || child.id === 'potctl/introduction'),
  );
}

function isPotctlCliCategory(item) {
  if (!item || item.type !== 'category') {
    return false;
  }
  const linkId = item.link && item.link.id;
  const hasDir = (item.items || []).some(
    (child) => child.type === 'autogenerated' && POTCTL_CLI_DIRS[child.dirName],
  );
  return linkId === 'potctl/cli/potctl' || hasDir;
}

function retargetCliCategory(item) {
  const next = {
    ...item,
    label:
      item.label === 'potctl CLI Reference'
        ? 'iofogctl CLI Reference'
        : item.label === 'potctl'
          ? 'iofogctl'
          : item.label,
  };
  if (next.link && next.link.id === 'potctl/cli/potctl') {
    next.link = {...next.link, id: 'iofogctl/cli/iofogctl'};
  }
  next.items = (next.items || []).map((child) => {
    const retargeted = child.type === 'autogenerated' && POTCTL_CLI_DIRS[child.dirName];
    if (retargeted) {
      return {...child, dirName: POTCTL_CLI_DIRS[child.dirName]};
    }
    return child;
  });
  return next;
}

function mapItems(items, mode) {
  if (!Array.isArray(items)) {
    return items;
  }
  const out = [];
  for (const item of items) {
    if (isPotctlCliCategory(item)) {
      if (mode === 'strip') {
        continue;
      }
      out.push(retargetCliCategory(item));
      continue;
    }
    if (mode === 'retarget' && isCliGuidesCategory(item)) {
      out.push({...item, label: 'iofogctl', items: mapItems(item.items, mode)});
      continue;
    }
    if (item && Array.isArray(item.items)) {
      out.push({...item, items: mapItems(item.items, mode)});
    } else {
      out.push(item);
    }
  }
  return out;
}

function patchSidebar(sidebar, mode) {
  if (Array.isArray(sidebar)) {
    return mapItems(sidebar, mode);
  }
  const next = {};
  for (const [key, value] of Object.entries(sidebar)) {
    next[key] = Array.isArray(value) ? mapItems(value, mode) : value;
  }
  return next;
}

function writePatched(file, mode) {
  const sidebarPath = path.join(SIDEBARS_DIR, file);
  const bak = backupPath(file);
  if (!fs.existsSync(sidebarPath)) {
    throw new Error(`Missing sidebar file: ${sidebarPath}`);
  }
  if (!fs.existsSync(bak)) {
    fs.copyFileSync(sidebarPath, bak);
  }
  const sidebar = JSON.parse(fs.readFileSync(bak, 'utf8'));
  fs.writeFileSync(sidebarPath, `${JSON.stringify(patchSidebar(sidebar, mode), null, 2)}\n`);
}

function restoreFile(file) {
  const sidebarPath = path.join(SIDEBARS_DIR, file);
  const bak = backupPath(file);
  if (!fs.existsSync(bak)) {
    return false;
  }
  fs.copyFileSync(bak, sidebarPath);
  fs.rmSync(bak, {force: true});
  return true;
}

function main() {
  const action = process.argv[2];
  if (action !== 'patch' && action !== 'restore') {
    throw new Error('Usage: flavor-version-sidebar.js patch|restore');
  }

  if (action === 'patch') {
    if (process.env.DOCUSAURUS_DISTRIBUTION !== 'iofog') {
      return;
    }
    for (const {file, mode} of FILES) {
      writePatched(file, mode);
    }
    console.log('flavor-version-sidebar: patched version sidebars for ioFog');
    return;
  }

  const restored = FILES.filter(({file}) => restoreFile(file)).length;
  if (restored) {
    console.log('flavor-version-sidebar: restored version sidebars');
  }
}

main();
